#!/usr/bin/env python3
"""Generate an exhaustive, named observer for one already-elaborated model.

No RTL edits, Verilator invocation, pointer dumps, or hand-selected signal list.
Fail closed on unfamiliar design-state declarations. Output is a build artifact.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path


def generate(obj):
    header = obj / 'Vsystem___024root.h'
    source = header.read_text()
    state = source.split('// DESIGN SPECIFIC STATE', 1)[1].split('// INTERNAL VARIABLES', 1)[0]
    fields, excluded = [], []
    for line in state.splitlines():
        line = line.strip()
        if not line or line.startswith('//') or line in ('struct {', '};'):
            continue
        port = re.fullmatch(r'VL_(?:IN|OUT|INOUT)(?:8|16|64|W)?\((\w+),.*\);', line)
        data = re.fullmatch(r'((?:CData|SData|IData|QData|VlWide|VlUnpacked|bool|double|uint\d+_t).*?)\s+(\w+);', line)
        if port:
            fields.append((port[1], line))
        elif data:
            fields.append((data[2], data[1]))
        elif line.startswith('VlNBACommitQueue<'):
            excluded.append(line)
        else:
            raise ValueError(f'unrecognized model state declaration: {line}')
    # Static parameter arrays are useful when reconstructing the full design view.
    fields += [(m[2], m[1]) for m in re.finditer(
        r'^\s*static constexpr (.+?) (\w+) =', source, re.M)]
    names = {name for name, _ in fields}
    assert len(names) == len(fields)
    serializer = (obj / 'Vsystem___024root__Slow.cpp').read_text().split(
        'void Vsystem___024root::__Vdeserialize', 1)[0]
    saved = set(re.findall(r'os\s*<<\s*(\w+)', serializer)) - {'__Vcheckval', 'vlSymsp'}
    if saved - names:
        raise ValueError(f'savable fields missing from observer: {sorted(saved - names)}')
    # This model has no other stateful cells. Refuse future hierarchical splits
    # instead of silently calling a root-only trace exhaustive.
    syms = (obj / 'Vsystem__Syms.h').read_text().split('// MODULE INSTANCE STATE')[1].split('// SCOPE NAMES')[0]
    cells = re.findall(r'(Vsystem_\w+)\s+(\w+);', syms)
    for cls, instance in cells:
        if instance == 'TOP':
            continue
        cell = (obj / (cls + '.h')).read_text()
        if '// DESIGN SPECIFIC STATE' in cell:
            raise ValueError(f'additional stateful cell needs enumeration: {instance}')
    digest = hashlib.sha256(header.read_bytes()).hexdigest()
    out = ['// Generated by tools/gen_state_delta.py; never edit.',
           f'// Root header SHA256: {digest}']
    for name, typ in fields:
        out.append(f'delta.add({json.dumps(name)}, r->{name}, {json.dumps(typ)});')
    (obj / 'ven_state_fields.inc').write_text('\n'.join(out) + '\n')
    audit = dict(root_header_sha256=digest, fields=len(fields),
                 serializer_fields=len(saved), all_serializer_fields_covered=True,
                 excluded_scheduler_queues=excluded,
                 boundary='All retained numeric RTL fields, ports, arrays, constants and generated scalar temporaries. '
                          'No optimized-away signals, host pointers, scheduler allocation objects, or external DDR/PS/disk state. '
                          'Sample only after eval settles; queue effects are in their destination arrays.')
    (obj / 'ven_state_fields.audit.json').write_text(json.dumps(audit, indent=2) + '\n')
    print(json.dumps({k: v for k, v in audit.items() if k != 'excluded_scheduler_queues'}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('objdir', type=Path)
    generate(parser.parse_args().objdir)
