#!/usr/bin/env python3
"""Render the key resources from a Vivado utilization report as an SVG.

The chart deliberately reports *placed* utilization when its input is a placed
report.  It is a visual summary, not timing or DRC sign-off.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from xml.sax.saxutils import escape


ROWS = (
    ("CLB LUTs", "CLB LUTs", "#d04b4b"),
    ("CLB sites", "CLB", "#e8893a"),
    ("Registers", "CLB Registers", "#5b9bd5"),
    ("Block RAM", "Block RAM Tile", "#70ad47"),
    ("DSP", "DSPs", "#8064a2"),
)


def parse_table(report: str) -> dict[str, tuple[int, int, float]]:
    """Read the six-column utilization rows needed for the compact chart."""

    values: dict[str, tuple[int, int, float]] = {}
    wanted = {source for _, source, _ in ROWS}
    for line in report.splitlines():
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 6 or cells[0] not in wanted or cells[0] in values:
            continue
        if not re.fullmatch(r"[\d,]+", cells[1]) or not re.fullmatch(r"[\d,]+", cells[4]):
            continue
        try:
            values[cells[0]] = (
                int(cells[1].replace(",", "")),
                int(cells[4].replace(",", "")),
                float(cells[5]),
            )
        except ValueError:
            continue
    missing = wanted - values.keys()
    if missing:
        raise ValueError(f"missing utilization rows: {', '.join(sorted(missing))}")
    return values


def header_value(report: str, label: str) -> str:
    match = re.search(rf"^\|\s*{re.escape(label)}\s*:\s*(.*?)\s*$", report, re.MULTILINE)
    return match.group(1) if match else "unknown"


def render(report_path: Path, output_path: Path) -> None:
    report = report_path.read_text(encoding="utf-8", errors="replace")
    values = parse_table(report)
    device = header_value(report, "Device")
    date = header_value(report, "Date")
    design = header_value(report, "Design")

    width, height = 1200, 560
    left, bar_width, top, step = 290, 760, 160, 68
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">',
        '<title id="title">Placed FPGA utilization</title>',
        '<desc id="desc">Vivado placed utilization for the current RK-XCZU15EG-F Ventium image.</desc>',
        '<rect width="1200" height="560" fill="#101820"/>',
        '<style>text{font-family:Inter,Arial,sans-serif;fill:#edf3f7}.muted{fill:#a7bbc8}.label{font-size:20px;font-weight:600}.value{font-size:19px;font-weight:700}.meta{font-size:16px}.foot{font-size:14px}</style>',
        '<text x="70" y="62" font-size="31" font-weight="700">RK-XCZU15EG-F FPGA utilization</text>',
        '<text class="meta muted" x="70" y="92">Placed design — utilization is not timing or functional sign-off</text>',
        f'<text class="meta muted" x="70" y="119">{escape(design)} · {escape(device)} · Vivado report dated {escape(date)}</text>',
    ]
    for index, (label, source, color) in enumerate(ROWS):
        used, available, percent = values[source]
        y = top + index * step
        filled = bar_width * percent / 100.0
        lines.extend(
            (
                f'<text class="label" x="70" y="{y + 25}">{escape(label)}</text>',
                f'<rect x="{left}" y="{y}" width="{bar_width}" height="34" rx="5" fill="#29404d"/>',
                f'<rect x="{left}" y="{y}" width="{filled:.1f}" height="34" rx="5" fill="{color}"/>',
                f'<text class="value" x="1070" y="{y + 25}">{percent:.2f}%</text>',
                f'<text class="foot muted" x="{left}" y="{y + 55}">{used:,} / {available:,}</text>',
            )
        )
    lines.extend(
        (
            '<line x1="70" y1="510" x2="1130" y2="510" stroke="#38505e"/>',
            f'<text class="foot muted" x="70" y="536">Generated by tools/render_fpga_utilization.py from {escape(report_path.as_posix())}</text>',
            '</svg>',
        )
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path, help="Vivado report_utilization output")
    parser.add_argument("output", type=Path, help="SVG chart to create")
    args = parser.parse_args()
    render(args.report, args.output)


if __name__ == "__main__":
    main()
