#!/usr/bin/env python3
"""Generate an exhaustive input-only snapshot from a Verilator model header.

Unknown port declarations, unpacked ports and inouts are deliberately fatal.
Never infer a subset from a historical top-level RTL interface: each generated
header is parsed afresh for the exact elaborated model used by the build.
"""

import argparse
import hashlib
from pathlib import Path
import re


def input_ports(header):
    regions = re.findall(r"// PORTS\b(.*?)// CELLS\b", header, re.DOTALL)
    if len(regions) != 1:
        raise ValueError("expected exactly one generated PORTS/CELLS region")
    region = re.sub(r"/\*.*?\*/", "", regions[0], flags=re.DOTALL)
    region = re.sub(r"//[^\n]*", "", region)
    ports = []
    names = set()
    declaration = re.compile(
        r"\s*VL_(IN|OUT)(8|16|64|W)?\(\s*&?([A-Za-z_]\w*)\s*,\s*(\d+)\s*,\s*(\d+)"
        r"(?:\s*,\s*(\d+))?\s*\)\s*;\s*")
    for line in region.splitlines():
        if not line.strip():
            continue
        match = declaration.fullmatch(line)
        if match is None:
            raise ValueError(f"unparsed or unsupported generated port: {line.strip()}")
        direction, kind, name, msb, lsb, words = match.groups()
        msb, lsb = int(msb), int(lsb)
        if msb < lsb or name in names:
            raise ValueError("invalid range or duplicate generated port")
        names.add(name)
        width = msb - lsb + 1
        if kind == "W":
            if words is None or int(words) != (width + 31) // 32 or width <= 64:
                raise ValueError("generated wide port has inconsistent word count")
            words = int(words)
        else:
            storage_width = int(kind or 32)
            if words is not None or width > storage_width:
                raise ValueError("generated scalar port has inconsistent width")
            words = 1
        if direction == "IN":
            ports.append({"name": name, "kind": kind or "32", "words": words,
                          "msb": msb, "lsb": lsb})
    if not ports or not any(port["name"] == "clk" for port in ports):
        raise ValueError("generated model has no complete input/clock interface")
    return ports


def generate(header):
    ports = input_ports(header)
    expressions = []
    for port in ports:
        expressions.extend(f"top.{port['name']}[{word}]" if port["kind"] == "W"
                           else f"top.{port['name']}" for word in range(port["words"]))
    values = ",\n".join(f"            static_cast<std::uint64_t>({expression})" for expression in expressions)
    digest = hashlib.sha256(header.encode()).hexdigest()
    return f"""// Generated by tools/gen_model_input_snapshot.py; do not edit.
// Complete generated model-header SHA256: {digest}
#pragma once
#include <array>
#include <cstddef>
#include <cstdint>

class ModelInputSnapshot {{
    std::array<std::uint64_t, {len(expressions)}> values_{{}};
    bool valid_ = false;
    template<class T> static auto observe(const T& top) noexcept {{
        return std::array<std::uint64_t, {len(expressions)}>{{{{
{values}
        }}}};
    }}
public:
    static constexpr std::size_t input_ports = {len(ports)};
    static constexpr std::size_t input_cells = {len(expressions)};
    template<class T> void capture(const T& top) noexcept {{
        values_ = observe(top);
        valid_ = true;
    }}
    template<class T> bool matches(const T& top) const noexcept {{
        return valid_ && values_ == observe(top);
    }}
}};
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-header", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        output = generate(args.model_header.read_text())
    except (OSError, ValueError) as error:
        parser.error(str(error))
    # Atomic generated build artifact, not an edit to a checked-in source file.
    temporary = args.output.with_name(args.output.name + ".new")
    temporary.write_text(output)
    temporary.replace(args.output)


if __name__ == "__main__":
    main()
