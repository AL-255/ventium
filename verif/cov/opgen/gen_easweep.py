"""Generate the EXHAUSTIVE ModRM/SIB effective-address sweep (verif/cov/opgen/
tests/ea_sweep). LEA computes the effective address WITHOUT touching memory, so
every 32-bit ModRM + SIB encoding can be swept with zero fault risk, and the
result is a deterministic function of the (known-initialised) GPRs, so it is
diff-checked against the QEMU golden per retire.

Covered (the full 32-bit memory-EA space — mod=11 register-direct is covered by
the per-opcode reg-direct cases, since LEA #UDs on mod=11):
  * mod=00/01/10 [base]            for every base reg (ESP -> SIB, EBP -> disp8)
  * mod=00 disp32 (no base)
  * SIB: scale {1,2,4,8} x index {7 regs + none} x base {8 regs} x mod {00,01,10}
This walks every architecturally-distinct ModRM and SIB byte.
"""
from __future__ import annotations
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "tests", "ea_sweep")

# index order = ModRM/SIB register encoding 0..7
REG = ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi"]
# known, distinct, non-overlapping init values so every EA is unique + bounded
INIT = {r: 0x1000 * (i + 1) for i, r in enumerate(REG)}
DEST = "edi"   # LEA result lands here; cascading is fine (QEMU matches identically)


def main():
    os.makedirs(OUT, exist_ok=True)
    L = []
    L.append("# Copyright 2026 Anhang Li (AL-255, thelithcore@gmail.com)")
    L.append("# SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1")
    L.append("# GENERATED by verif/cov/opgen/gen_easweep.py — exhaustive ModRM/SIB EA sweep.")
    L.append("    .text")
    L.append("    .globl _start")
    L.append("_start:")
    # init every GPR to a known value
    for r in REG:
        if r == "esp":
            continue            # keep a usable stack pointer
        L.append(f"    movl  ${INIT[r]:#x}, %{r}")

    n = 0
    def lea(form):
        nonlocal n
        L.append(f"    leal  {form}, %{DEST}")
        n += 1

    # ---- non-SIB: mod=00/01/10 [base] for base != ESP --------------------
    for disp in ("", "0x12", "0x12345678"):
        for b in REG:
            if b == "esp":
                continue        # ESP base is only reachable through SIB
            lea(f"{disp}(%{b})")
    # ---- mod=00 disp32, no base (ModRM rm=101) ---------------------------
    lea("0x12345678")

    # ---- SIB no-index (index=100): reached via an ESP base, which forces a
    #      SIB byte with index=100 (ESP cannot be a SIB index, so 'no index' is
    #      the only way the index=100 field is produced) -----------------------
    for disp in ("", "0x12", "0x12345678"):
        lea(f"{disp}(%esp)")

    # ---- SIB: scale x index x base x mod (ESP is not a legal index) --------
    for scale in (1, 2, 4, 8):
        for idx in [r for r in REG if r != "esp"]:
            for b in REG:
                for disp in ("", "0x12", "0x12345678"):
                    # mod=00 with base=EBP is encoded as disp32; gas handles it.
                    lea(f"{disp}(%{b},%{idx},{scale})")

    # exit
    L.append("    movl  $1, %eax")
    L.append("    xorl  %ebx, %ebx")
    L.append("    int   $0x80")
    open(os.path.join(OUT, "ea_sweep.s"), "w").write("\n".join(L) + "\n")

    import json
    json.dump({
        "name": "ea_sweep", "src": "ea_sweep/ea_sweep.s",
        "elf": "ea_sweep/ea_sweep.elf", "image": "ea_sweep/ea_sweep.flat",
        "load_addr": "0x08048000", "entry": "0x08048000",
        "max_insn": n + 16,
    }, open(os.path.join(OUT, "manifest.json"), "w"), indent=2)
    print(f"ea_sweep: {n} LEA forms (every ModRM/SIB EA) -> {OUT}/ea_sweep.s")


if __name__ == "__main__":
    main()
