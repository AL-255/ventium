"""Generate a MINIMAL runnable repro per cataloged finding (known_diverge.txt) —
the single instruction that halts/diverges, in the smallest program that reaches
it. The multi-case op_* test proves a finding exists; this isolates it to one
line so the RTL owner can debug the exact decode/exec path. Each repro prints
where the core stops vs what QEMU does.

Output: verif/cov/opgen/repros/<name>/repro.s (+ a manifest), and REPROS.md.
"""
from __future__ import annotations
import os, json

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "repros")

# finding -> (one-line description, the isolating instruction(s), x87?)
# prologue gives a 64-byte stack buffer at %esi (mapped, writable).
REPROS = {
    "bt_mem":     ("BT  Ev,Gv  with a memory operand HALTs (reg-direct works)",
                   ["    btl   %eax, (%esi)"], False),
    "bts_mem":    ("BTS Ev,Gv  memory HALTs", ["    btsl  %eax, (%esi)"], False),
    "btr_mem":    ("BTR Ev,Gv  memory HALTs", ["    btrl  %eax, (%esi)"], False),
    "btc_mem":    ("BTC Ev,Gv  memory HALTs", ["    btcl  %eax, (%esi)"], False),
    "bt_imm_mem": ("BT  Ev,Ib  memory HALTs", ["    btl   $1, (%esi)"], False),
    "shld_mem":   ("SHLD Ev,Gv,Ib memory HALTs (reg-direct works)",
                   ["    shldl $4, %eax, (%esi)"], False),
    "shrd_mem":   ("SHRD Ev,Gv,Ib memory HALTs", ["    shrdl $4, %eax, (%esi)"], False),
    "pop_es":     ("POP ES HALTs (segment POP gap)", ["    pushl %eax", "    pop   %es"], False),
    "pop_ss":     ("POP SS HALTs", ["    pushl %eax", "    pop   %ss"], False),
    "pop_ds":     ("POP DS HALTs", ["    pushl %eax", "    pop   %ds"], False),
    "pop_gs":     ("POP GS HALTs (0F A9)", ["    pushl %eax", "    pop   %gs"], False),
    "fsin":       ("FSIN deferred->HALT without VEN_TRANSCENDENTAL",
                   ["    finit", "    fldpi", "    fsin"], True),
    "fcos":       ("FCOS deferred->HALT", ["    finit", "    fld1", "    fcos"], True),
    "f2xm1":      ("F2XM1 deferred->HALT", ["    finit", "    fldz", "    f2xm1"], True),
    "fptan":      ("FPTAN deferred->HALT", ["    finit", "    fld1", "    fptan"], True),
    "fsin_inf":   ("FSIN of +inf HALTs (feature build): IEEE special-input gap — "
                   "should set C2+return NaN, not halt",
                   ["    finit", "    fldl 1f", "    fsin", "    jmp 2f",
                    "    .align 8", "1:  .quad 0x7FF0000000000000", "2:"], True),
    "fxtract":    ("FXTRACT HALTs even WITH +VEN_TRANSCENDENTAL (genuine gap; it is an "
                   "exact exponent/mantissa split, not an approximation)",
                   ["    finit", "    fldpi", "    fxtract"], True),
    "mov_moffs":  ("MOV moffs (A0) not decoded -> HALT (raw bytes A0+disp32)",
                   ["    .byte 0xa0, 0x00, 0x00, 0x04, 0x08"], False),
}


def write(name, desc, lines, x87):
    d = os.path.join(OUT, name)
    os.makedirs(d, exist_ok=True)
    body = ["# Copyright 2026 Anhang Li (AL-255, thelithcore@gmail.com)",
            "# SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1",
            f"# MINIMAL REPRO: {desc}",
            "    .text", "    .globl _start", "_start:",
            "    xorl  %eax, %eax",
            "    subl  $64, %esp",
            "    movl  %esp, %esi",
            "    movl  $0x11223344, (%esi)"] + lines + [
            "    addl  $64, %esp",
            "    movl  $1, %eax", "    xorl  %ebx, %ebx", "    int   $0x80"]
    open(os.path.join(d, "repro.s"), "w").write("\n".join(body) + "\n")
    json.dump({"name": "repro_" + name, "src": "repro.s", "x87": x87}, open(os.path.join(d, "manifest.json"), "w"))


# Findings that only manifest in real/protected mode (need a mode-stream context,
# not a flat user-mode .s) — their repro VEHICLE is the named mode image: add the
# halting instruction back to that stream and it stops there. Indexed here so the
# RTL owner has one complete finding->repro map.
MODE_FINDINGS = {
    "clts":   ("CLTS (0F 06) HALTs",            "modes/realmode_priv", "clts"),
    "lmsw":   ("LMSW (0F 01 /6) HALTs",         "modes/realmode_priv", "smsww %ax; lmsw %ax"),
    "invlpg": ("INVLPG (0F 01 /7) HALTs",       "modes/realmode_priv", "invlpg 0x600"),
    "lar":    ("LAR (0F 02) HALTs (PM only)",   "modes/pm32_cpl0",     "lar %ax, %ebx"),
    "lsl":    ("LSL (0F 03) HALTs (PM only)",   "modes/pm32_cpl0",     "lsl %ax, %ebx"),
    "verr":   ("VERR (0F 00 /4) HALTs (PM)",    "modes/pm32_cpl0",     "verr %ax"),
    "verw":   ("VERW (0F 00 /5) HALTs (PM)",    "modes/pm32_cpl0",     "verw %ax"),
    "sldt":   ("SLDT (0F 00 /0) HALTs (PM)",    "modes/pm32_cpl0",     "sldt %dx"),
    "str":    ("STR (0F 00 /1) HALTs (PM)",     "modes/pm32_cpl0",     "str %bp"),
}


def main():
    os.makedirs(OUT, exist_ok=True)
    md = ["<!-- generated by gen_repros.py -->", "# Finding repros (complete index)", "",
          "## User-mode (flat) — runnable minimal repros",
          "Each is the single instruction that halts/diverges, isolated. Build with",
          "`gcc -m32 -nostdlib -static -Wl,-Ttext=0x08048000` and run the core TB.", ""]
    for name, (desc, lines, x87) in REPROS.items():
        write(name, desc, lines, x87)
        md.append(f"* **{name}** — {desc}\n  ```\n  " + "\n  ".join(l.strip() for l in lines) + "\n  ```")
    md += ["", "## Real/Protected-mode findings — repro via the mode stream",
           "Add the instruction back to the named image (`gen_modes.py`) and run",
           "`run-modes.sh`; the core halts at that instruction vs qemu-system.", ""]
    for name, (desc, img, insn) in MODE_FINDINGS.items():
        md.append(f"* **{name}** — {desc} — vehicle `{img}` — `{insn}`")
    open(os.path.join(HERE, "REPROS.md"), "w").write("\n".join(md) + "\n")
    print(f"wrote {len(REPROS)} user-mode repros + {len(MODE_FINDINGS)} mode-finding index -> REPROS.md")


if __name__ == "__main__":
    main()
