#!/usr/bin/env python3
"""Extract the live segment-extent declaration and mux for a tiny guard TB."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import sys


DECLARATION = re.compile(
    r"^[ \t]*wire[ \t]+\[7:0\][ \t]+seg_ext_size[ \t]*;[^\n]*$", re.MULTILINE
)
ASSIGNMENT = re.compile(
    r"^[ \t]*assign[ \t]+seg_ext_size[ \t]*=[^;]+;", re.MULTILINE
)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--core", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    source = args.core.read_text(encoding="utf-8")
    declarations = DECLARATION.findall(source)
    assignments = ASSIGNMENT.findall(source)
    if len(declarations) != 1:
        raise ValueError(f"expected one seg_ext_size declaration, found {len(declarations)}")
    if len(assignments) != 1:
        raise ValueError(f"expected one seg_ext_size assignment, found {len(assignments)}")
    assignment = assignments[0]
    required_rhs = "seg_ext_ovr_v ? seg_ext_ovr : {4'd0, cur_size}"
    if required_rhs not in assignment:
        raise ValueError("seg_ext_size assignment is not the expected override-or-cur_size mux")

    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        "// AUTOGENERATED: do not edit.\n"
        f"// core.sv sha256: {digest}\n"
        f"{declarations[0]}\n{assignment}\n",
        encoding="utf-8",
    )
    print(f"SEG-EXT-SIZE-EXTRACT-OK core_sha256={digest}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as exc:
        print(f"SEG-EXT-SIZE-EXTRACT-FAIL: {exc}", file=sys.stderr)
        raise SystemExit(2)
