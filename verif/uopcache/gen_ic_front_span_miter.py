#!/usr/bin/env python3
"""Extract the production IC-front span and its pre-change oracle functions.

The accompanying miter deliberately does not carry a copied implementation of
the optimized frontend.  It includes the exact marked section from core.sv,
and the three original lookup functions from the same source revision.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import sys


BEGIN = "// BEGIN IC FRONT SPAN"
END = "// END IC FRONT SPAN"
FUNCTIONS = (
    "function automatic logic ic_present",
    "function automatic logic [IC_WAYW-1:0] ic_hit_way",
    "function automatic logic [7:0] ic_byte",
)
REQUIRED = (
    "`ifdef VEN_IC_BRAM",
    "localparam int IC_FRONT_BYTES = 22;",
    "function automatic logic [IC_WAYW:0] ic_front_probe",
    "ic_front_a = ic_front_probe(flin)",
    "ic_front_b = ic_front_probe(flin_nl)",
    "ic_front_bytes",
    "ic_front_present_bytes",
)
V_INDEX_CONTRACT = re.compile(
    r"for \(int i=0;i<7;i\+\+\) vb\[i\] = "
    r"ic_front_bytes\[\{1'b0,(u_d(?:_ref)?\.len)\}\+5'\(i\)\];"
)


def function_text(source: str, signature: str) -> str:
    start = source.find(signature)
    if start < 0:
        raise ValueError(f"missing production oracle function: {signature}")
    end = source.find("endfunction", start)
    if end < 0:
        raise ValueError(f"unterminated production oracle function: {signature}")
    return source[start : end + len("endfunction")]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--core", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    source = args.core.read_text(encoding="utf-8")
    first = source.find(BEGIN)
    last = source.find(END, first if first >= 0 else 0)
    if first < 0 or last < 0 or source.find(BEGIN, first + 1) >= 0:
        raise ValueError("expected exactly one IC FRONT SPAN marker pair")
    section = source[first : last + len(END)]
    for required in REQUIRED:
        if required not in section:
            raise ValueError(f"production span lacks required text: {required}")
    # The miter's V loop is intentionally a consumer-level equivalence check,
    # not a substitute for proving that core.sv wired V to the factored span.
    # Both production gather sites must retain the exact compact index form.
    v_index_operands = V_INDEX_CONTRACT.findall(source)
    if sorted(v_index_operands) != ["u_d.len", "u_d_ref.len"]:
        raise ValueError(
            "expected exact raw-V ic_front_bytes index contracts for u_d and u_d_ref"
        )

    oracle = "\n\n".join(function_text(source, signature) for signature in FUNCTIONS)
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    section_digest = hashlib.sha256(section.encode("utf-8")).hexdigest()
    output = (
        "// AUTOGENERATED: do not edit.\n"
        f"// core.sv sha256: {digest}\n"
        f"// IC FRONT SPAN sha256: {section_digest}\n"
        "// Raw-V consumer contracts: u_d_ref.len and u_d.len exact 5'(i) form.\n"
        "// Production oracle functions precede the exact production section.\n\n"
        + oracle
        + "\n\n"
        + section
        + "\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")
    print(f"IC-FRONT-SPAN-EXTRACT-OK core_sha256={digest} section_sha256={section_digest}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as exc:
        print(f"IC-FRONT-SPAN-EXTRACT-FAIL: {exc}", file=sys.stderr)
        raise SystemExit(2)
